import { Question } from "../pages/quiz/quiz.types";

export function shuffleArray (arr: Question[]): Question[]  {
  const newArr = [...arr];
  for (let i = newArr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [newArr[i], newArr[j]] = [newArr[j], newArr[i]];
  }
  return newArr;
}
